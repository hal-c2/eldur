#!/usr/bin/env python3
"""Print crates/eldur_convert/src/emit/qt_members.rs from Qt 6's .qmltypes.

An id named like a property of an object in whose scope it is read shadows
that property, and qmllint reports it (`id-shadows-member`). The converter
keeps its ids off these names. Run with the QML import directory of the Qt
the converter targets:

    python3 tools/qt-members/generate.py /usr/lib/qt6/qml > crates/eldur_convert/src/emit/qt_members.rs
"""
import re
import sys
from pathlib import Path

# The Qt types the converter writes (`grep -ho '[A-Z][A-Za-z]* {'` over the
# corpus output), by module. Controls come from QtQuick.Templates, which the
# Basic style's types derive from without adding properties of their own.
TYPES = {
    "QtQuick": ["Item", "Text", "Rectangle", "Image", "Flickable", "Flow", "Repeater",
                "Canvas", "FontMetrics", "TextMetrics", "TapHandler", "HoverHandler",
                "WheelHandler", "PointHandler", "Translate", "Rotation", "Scale",
                "Matrix4x4", "ShaderEffect", "GradientStop", "Gradient",
                "NumberAnimation", "ColorAnimation", "SequentialAnimation",
                "ParallelAnimation", "PropertyAction", "PauseAnimation", "Behavior",
                "State", "PropertyChanges", "Transition", "MouseArea", "Loader",
                "TextInput", "TextEdit", "PathRectangle", "PathLine"],
    "QML": ["QtObject", "Component"],
    "QtQml": ["Connections", "Timer"],
    "QtQuick.Layouts": ["ColumnLayout", "RowLayout", "GridLayout"],
    "QtQuick.Shapes": ["Shape", "ShapePath"],
    "QtQuick.Effects": ["MultiEffect", "RectangularShadow"],
    "QtQuick.Templates": ["ApplicationWindow", "Button", "TextField", "TextArea",
                          "CheckBox", "RadioButton", "ProgressBar", "SpinBox",
                          "ComboBox", "Slider", "ScrollView", "GroupBox",
                          "ButtonGroup", "ScrollBar", "Popup", "Label"],
}


def components(text):
    """Each top-level Component: its name, prototype, exports and property names."""
    out = []
    # Blocks nest by braces; a Component's own fields sit at its first level.
    for body in top_level_blocks(text, "Component"):
        c = {"name": None, "prototype": None, "exports": [], "props": []}
        level = []
        depth = 0
        for ch in body:
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            elif depth == 0:
                level.append(ch)
        own = "".join(level)
        for key in ("name", "prototype"):
            m = re.search(rf'(?m)^\s*{key}: "([^"]*)"', own)
            if m:
                c[key] = m.group(1)
        m = re.search(r"exports: \[([^\]]*)\]", own)
        if m:
            c["exports"] = re.findall(r'"([^"]+)"', m.group(1))
        c["props"] = re.findall(r'Property \{[^}]*?\bname: "([^"]+)"', body)
        out.append(c)
    return out


def top_level_blocks(text, keyword):
    """The bodies of `keyword { ... }` blocks one level inside the file's Module."""
    blocks = []
    depth = 0
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == "{":
            head = text[max(0, i - 40):i].rstrip()
            depth += 1
            if depth == 2 and head.endswith(keyword):
                start = i + 1
                inner = 1
                j = start
                while inner:
                    if text[j] == "{":
                        inner += 1
                    elif text[j] == "}":
                        inner -= 1
                    j += 1
                blocks.append(text[start:j - 1])
                i = j
                depth -= 1
                continue
        elif ch == "}":
            depth -= 1
        i += 1
    return blocks


def main():
    root = Path(sys.argv[1])
    by_name = {}
    exported = {}
    for path in sorted(root.rglob("*.qmltypes")):
        for c in components(path.read_text()):
            by_name.setdefault(c["name"], c)
            for e in c["exports"]:
                module, _, rest = e.partition("/")
                exported.setdefault((module, rest.split(" ")[0]), c)
    names = set()
    for module, types in TYPES.items():
        for t in types:
            c = exported.get((module, t))
            if c is None:
                sys.exit(f"{module}/{t} not found under {root}")
            while c is not None:
                names.update(c["props"])
                c = by_name.get(c["prototype"]) if c["prototype"] else None
    words = sorted(n for n in names if re.fullmatch(r"[a-z][A-Za-z0-9]*", n))
    print("// @generated by tools/qt-members/generate.py from Qt's .qmltypes; do not edit.")
    print()
    print("/// Property names of the Qt types the converter writes, sorted.")
    print("pub(crate) const QT_MEMBERS: &[&str] = &[")
    for w in words:
        print(f'    "{w}",')
    print("];")


main()
